#!/usr/bin/env python3
"""Generate Motion Studio tool help and check code/documentation changes together.

Uses only Python's standard library and Git. Never executes media jobs, installs
plugins, changes profiles, stages files or publishes source.
"""
from __future__ import annotations

import argparse
import ast
import difflib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ('docs/reference/tools.md', 'docs/reference/tool-schemas.json')
HOOK_MARKER = '# motion-studio documentation hook'


def git(*args, root=ROOT):
    return subprocess.check_output(['git', '-C', str(root), *args])


class WithoutDocstrings(ast.NodeTransformer):
    def strip(self, node):
        self.generic_visit(node)
        if node.body and isinstance(node.body[0], ast.Expr) and isinstance(node.body[0].value, ast.Constant) and isinstance(node.body[0].value.value, str):
            node.body.pop(0)
        return node

    def visit_Module(self, node):
        return self.strip(node)

    def visit_FunctionDef(self, node):
        return self.strip(node)

    def visit_AsyncFunctionDef(self, node):
        return self.strip(node)

    def visit_ClassDef(self, node):
        return self.strip(node)


def behavior_changed(path, before, after):
    """Conservative change detector, not proof of semantic equivalence."""
    if before == after:
        return False
    if before is None or after is None:
        return True
    if path.endswith('.py'):
        def normalized(value):
            return ast.dump(WithoutDocstrings().visit(ast.parse(value)), include_attributes=False)
        return normalized(before) != normalized(after)
    if path.endswith('.json'):
        return json.loads(before) != json.loads(after)
    return True


def is_functional(path):
    return (path in ('__init__.py', 'plugin.yaml', 'studio-manifest.json', 'requirements-test.txt')
            or path.startswith('skills/')
            or path.startswith(('studio/', 'desktop/', 'dashboard/', 'schemas/', 'skills/', 'scripts/', 'tools/', '.github/workflows/'))
            and not path.endswith('.md'))


def is_narrative(path):
    if path in ('README.md', 'CONTRIBUTING.md'):
        return True
    if path.startswith('tools/') and path.endswith('/README.md'):
        return True
    if not path.startswith('docs/') or not path.endswith('.md'):
        return False
    return len(Path(path).parts) == 2 or path.startswith(('docs/specification/', 'docs/ui/'))


def catalogue():
    # The real registration builds schemas only. Capturing ctx avoids handlers,
    # ProjectStore, plugin hooks and Hermes imports/installation.
    sys.path.insert(0, str(ROOT))
    from studio.tools import register_tools
    schemas = {}

    class Catalogue:
        def register_tool(self, name, schema, **_kwargs):
            if name in schemas:
                raise ValueError('Duplicate tool: ' + name)
            schemas[name] = schema

        def register_hook(self, _name, _handler, **_kwargs):
            # Documentation captures declarations; never run lifecycle hooks.
            pass

    register_tools(Catalogue())
    return schemas


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def field_type(schema, root=None, seen=frozenset()):
    if '$ref' in schema:
        reference = schema['$ref']
        if root is not None and reference.startswith('#/') and reference not in seen:
            target = root
            for part in reference[2:].split('/'):
                target = target[part.replace('~1', '/').replace('~0', '~')]
            return field_type(target, root, seen | {reference})
        return reference.rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=True)
    if 'enum' in schema:
        return ' / '.join(json.dumps(v, ensure_ascii=True) for v in schema['enum'])
    if 'anyOf' in schema or 'oneOf' in schema:
        return ' or '.join(dict.fromkeys(field_type(s, root, seen) for s in schema.get('anyOf', schema.get('oneOf', []))))
    kind = schema.get('type', 'object')
    if kind == 'array':
        return 'array of ' + field_type(schema.get('items', {}), root, seen)
    if kind == 'object' and schema.get('properties'):
        return 'object {' + ', '.join(schema['properties']) + '}'
    return str(kind)


def reference_files():
    schemas = catalogue()
    lines = ['# Registered tool reference', '',
             '<!-- Generated by scripts/docs.py reference. Do not edit by hand. -->', '',
             'These are the schemas published by native `register_tools`, not an',
             'inventory of guaranteed executable routes. Read [Hermes usage](../hermes.md)',
             'for workflow and authority boundaries, and [contracts](../specification/03-contracts.md)',
             'for result envelopes and domain rules.', '',
             '[Complete machine-readable schemas](tool-schemas.json) preserve nested',
             'objects, constraints, defaults, local references and action alternatives.',
             'Required/optional fields below apply to that exact alternative only;',
             'alternatives with the same action are distinct request shapes.', '',
             'Regenerate: `python scripts/docs.py reference`.',
             'Verify without writing: `python scripts/docs.py reference --check`.', '']
    for name, schema in schemas.items():
        lines.extend(['## ' + name, '', schema['description'], ''])
        params = schema['parameters']
        alternatives = params.get('oneOf', [params])
        for number, alternative in enumerate(alternatives):
            properties = alternative.get('properties', {})
            action = properties.get('action', {})
            label = action.get('const', ', '.join(action.get('enum', []))) or 'request'
            pointer = '/' + name + '/parameters' + ('/oneOf/' + str(number) if 'oneOf' in params else '')
            lines.extend(['### ' + str(label) + ' (alternative ' + str(number + 1) + ')', '',
                          'JSON pointer: `' + pointer + '`.', '',
                          '| Field | Required | Type / allowed values |',
                          '|---|---|---|'])
            for field, definition in properties.items():
                lines.append('| `' + cell(field) + '` | ' + ('yes' if field in alternative.get('required', []) else 'no') + ' | ' + cell(field_type(definition, params)) + ' |')
            lines.append('')
    from studio.contracts import D, PROJECT_SCHEMA
    from studio.project import ProjectStore
    project_documents = ('brief', 'brand', 'settings', 'bindings', 'timeline', 'scene',
                         'delivery_profile', 'gate_policy', 'variants', 'asset_library',
                         'storyboard', 'creative_plan', 'editorial')
    draft = {'$schema': 'https://json-schema.org/draft/2020-12/schema', '$defs': D}
    packaged = {
        'project-request': PROJECT_SCHEMA,
        'project-document': dict(draft, oneOf=[ProjectStore._document_schema(kind) for kind in project_documents]),
        'project-record': dict(draft, **{'$ref': '#/$defs/ProjectRecord'}),
        'project-snapshot': dict(draft, **{'$ref': '#/$defs/ProjectSnapshot'}),
        'project-transaction': dict(draft, oneOf=[{'$ref': '#/$defs/' + name}
            for name in ('ProjectTransaction', 'CreateCommit', 'ProjectNoop')]),
    }
    from studio.captions import schema_document
    for contract, filename in (
        ('CaptionDocument', 'caption-document'), ('CaptionStyle', 'caption-style'),
        ('CaptionPlacement', 'caption-placement'), ('CaptionTimingDecision', 'caption-timing-decision'),
        ('CaptionRequest', 'caption-request'), ('CaptionTransaction', 'caption-transaction'),
    ):
        packaged[filename] = schema_document(contract)
    result = {REFERENCE[0]: '\n'.join(lines),
              REFERENCE[1]: json.dumps(schemas, indent=2, sort_keys=True, ensure_ascii=True, allow_nan=False) + '\n'}
    result.update({'schemas/' + name + '.json': json.dumps(value, indent=2,
                   ensure_ascii=True, allow_nan=False) + '\n' for name, value in packaged.items()})
    return result


def reference(check=False):
    errors = []
    for name, text in reference_files().items():
        path = ROOT / name
        if check:
            if not path.is_file() or path.read_bytes() != text.encode('ascii'):
                errors.append(name + ' is missing or stale; run python scripts/docs.py reference')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='ascii')
            print('Generated ' + name)
    return errors


def changed_paths(base, staged):
    paths = set(git('diff', '--name-only', '-z', '--no-renames', *(['--cached'] if staged else []), base, '--').decode().split('\0'))
    if not staged:
        paths.update(git('ls-files', '--others', '--exclude-standard', '-z').decode().split('\0'))
    return sorted(paths - {''})


def blob(revision, path):
    result = subprocess.run(['git', '-C', str(ROOT), 'show', revision + ':' + path], capture_output=True)
    if result.returncode:
        # A missing blob is a valid addition/deletion. Other Git failures must
        # not silently turn into an empty baseline.
        probe = subprocess.run(['git', '-C', str(ROOT), 'cat-file', '-e', revision + ':' + path], capture_output=True)
        if probe.returncode == 128 and (b'does not exist' in probe.stderr or b'not in the index' in probe.stderr or b'exists on disk, but not in' in probe.stderr):
            return None
        raise RuntimeError(result.stderr.decode(errors='replace').strip())
    return result.stdout


def doc_errors(root, paths, baseline):
    errors = []
    # Check the maintained entry points plus changed current docs. Frozen
    # evidence retains historical host paths and is intentionally not rewritten.
    names = set(path for path in paths if is_narrative(path))
    names.update(('README.md', 'CONTRIBUTING.md', 'docs/README.md', 'docs/hermes.md', 'docs/documentation.md', REFERENCE[0]))
    for name in sorted(names):
        path = root / name
        if not path.is_file():
            if name in paths:
                continue  # Removed/renamed documentation is handled by Git.
            # Small fixture repositories need not contain all public guides.
            continue
        try:
            text = path.read_text(encoding='utf-8')
        except UnicodeDecodeError:
            errors.append(name + ': documentation must be UTF-8 with new/modified lines in ASCII')
            continue
        before = (blob(baseline, name) or b'').decode('utf-8')
        old_lines, new_lines = before.splitlines(), text.splitlines()
        changes = difflib.SequenceMatcher(None, old_lines, new_lines, autojunk=False)
        if any(not line.isascii()
               for tag, _a, _b, start, end in changes.get_opcodes() if tag in ('insert', 'replace')
               for line in new_lines[start:end]):
            errors.append(name + ': new/modified documentation lines must be ASCII')
        for target in re.findall(r'\[[^\]\n]+\]\(([^)\s]+)\)', text):
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or not parsed.path or parsed.path.startswith('/'):
                continue
            dest = path.parent / unquote(parsed.path)
            # Existing evidence links name local-only runtime receipts/media.
            if 'docs/evidence/' in str(dest):
                continue
            if not dest.exists():
                errors.append(name + ': missing local link ' + target)
    return errors


def check(base=None, staged=False):
    # Resolve before blob reads; reject invalid or absent CI baselines loudly.
    baseline = git('rev-parse', '--verify', (base or 'HEAD') + '^{commit}').decode().strip()
    paths = changed_paths(baseline, staged)
    functional = []
    narrative = []
    errors = []
    for path in paths:
        if not (is_functional(path) or is_narrative(path)):
            continue
        before = blob(baseline, path)
        after = blob('', path) if staged else ((ROOT / path).read_bytes() if (ROOT / path).is_file() else None)
        if is_narrative(path) and after is not None and before != after:
            narrative.append(path)
        if is_functional(path):
            try:
                if behavior_changed(path, before, after):
                    functional.append(path)
            except (SyntaxError, ValueError) as exc:
                errors.append(path + ': cannot compare source: ' + str(exc))
    if functional and not narrative:
        errors.append('Functionality changed without a human-written current documentation update:\n  ' + '\n  '.join(functional) + '\nUpdate the affected README, Hermes guide, operations or contracts in the same change; generated help alone is not enough.')
    if staged:
        # Check generated help and links against the exact index. Never import
        # worktree modules to validate staged code or accept unstaged docs.
        with tempfile.TemporaryDirectory(prefix='motion-docs-index-') as directory:
            snapshot = Path(directory)
            git('checkout-index', '--all', '--prefix=' + str(snapshot) + os.sep)
            script = snapshot / 'scripts/docs.py'
            if not script.is_file():
                errors.append('Stage scripts/docs.py before using the documentation hook.')
            else:
                env = dict(os.environ, PYTHONPATH=str(snapshot), PYTHONDONTWRITEBYTECODE='1')
                result = subprocess.run([sys.executable, str(script), 'reference', '--check'], cwd=snapshot, env=env, text=True, capture_output=True)
                if result.returncode:
                    errors.append((result.stdout + result.stderr).strip())
            errors.extend(doc_errors(snapshot, paths, baseline))
    else:
        errors.extend(reference(check=True))
        errors.extend(doc_errors(ROOT, paths, baseline))
    if not errors:
        print('Documentation check passed (' + str(len(functional)) + ' functionality files; ' + str(len(narrative)) + ' current documentation files changed).')
    return errors


def install_hook(force=False):
    # Respect a custom hooks path; never change global/local Git config.
    hooks = Path(git('rev-parse', '--git-path', 'hooks').decode().strip())
    if not hooks.is_absolute():
        hooks = ROOT / hooks
    target = hooks / 'pre-commit'
    if target.exists() and HOOK_MARKER not in target.read_text() and not force:
        raise ValueError('Existing pre-commit hook preserved. Chain python scripts/docs.py check --staged yourself, or explicitly use install-hook --force.')
    hooks.mkdir(parents=True, exist_ok=True)
    target.write_text('#!/bin/sh\n' + HOOK_MARKER + '\n' +
                      'root=$(git rev-parse --show-toplevel) || exit $?\n' +
                      'exec ' + shlex.quote(sys.executable) + ' "$root/scripts/docs.py" check --staged\n', encoding='utf-8')
    target.chmod(0o755)
    print('Installed local hook: ' + str(target))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    generate = commands.add_parser('reference', help='Generate real registered tool help; no media execution')
    generate.add_argument('--check', action='store_true', help='Fail on stale generated files without writing')
    verify = commands.add_parser('check', help='Check reference freshness and code/documentation changes')
    scope = verify.add_mutually_exclusive_group()
    scope.add_argument('--base', help='Compare this commit to the working tree (CI: event base SHA)')
    scope.add_argument('--staged', action='store_true', help='Check only staged files and generate from an index snapshot')
    hook = commands.add_parser('install-hook', help='Install an optional local pre-commit check; no Git config edits')
    hook.add_argument('--force', action='store_true', help='Explicitly replace a pre-existing hook')
    args = parser.parse_args()
    try:
        if args.command == 'reference':
            errors = reference(args.check)
        elif args.command == 'check':
            errors = check(args.base, args.staged)
        else:
            install_hook(args.force)
            errors = []
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as exc:
        errors = [str(exc)]
    for error in errors:
        print('ERROR: ' + error, file=sys.stderr)
    return 1 if errors else 0


if __name__ == '__main__':
    raise SystemExit(main())
